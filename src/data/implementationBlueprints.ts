function totalBudget(blueprint: Omit<ImplementationBlueprint, 'totalBudget' | 'totalCapitalRequired'>): ImplementationBlueprint {
  const total = blueprint.actions.reduce((s, a) => s + a.budgetAllocation, 0);
  const totalCapital = blueprint.actions.reduce((s, a) => s + a.capitalRequirement, 0);
  return { ...blueprint, totalBudget: total, totalCapitalRequired: totalCapital };
}

