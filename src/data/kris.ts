// Helper functions
export const getKRIById = (id: string): KRI | undefined => {
  return kris.find(kri => kri.id === id);
};

export const getKRIsByCategory = (category: KRI['category']): KRI[] => {
  return kris.filter(kri => kri.category === category);
};

export const getKRIsByStatus = (status: KRI['status']): KRI[] => {
  return kris.filter(kri => kri.status === status);
};

export const getBreachedKRIs = (): KRI[] => {
  return kris.filter(kri => kri.status === 'red');
};

export const getKRIStatusCounts = () => {
  return {
    green: kris.filter(k => k.status === 'green').length,
    amber: kris.filter(k => k.status === 'amber').length,
    red: kris.filter(k => k.status === 'red').length,
  };
};
