// Helper functions for risk data
export const getRiskById = (id: string): Risk | undefined => {
  return risks.find(risk => risk.id === id);
};

export const getRisksByCategory = (category: Risk['category']): Risk[] => {
  return risks.filter(risk => risk.category === category);
};

export const getRisksBySeverity = (severity: Risk['severity']): Risk[] => {
  return risks.filter(risk => risk.severity === severity);
};

export const getActiveRisks = (): Risk[] => {
  return risks.filter(risk => risk.status === 'active' || risk.status === 'escalated');
};

export const getHighPriorityRisks = (): Risk[] => {
  return risks.filter(risk => risk.severity === 'critical' || risk.severity === 'high');
};
